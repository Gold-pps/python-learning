"""能力说明的**唯一来源**（H4-1）。

为什么要有这个模块：第 24 周的真实使用里，使用者问过一句「你能回答什么问题？」——
系统照常走检索，回了一段资料摘录。因为能力边界当时只写在 `web/使用说明.md` 里、**界面里没有**：
使用者得先知道去翻文档，才问得出好问题；而"不知道能问什么"恰恰是新使用者的第一个问题
（见 `notes-qa/eval/第24周使用记录.md` 第五节）。

这个模块只做三件事，而且**只在这里做一次**（别在界面里再抄一份）：

1. 能答的范围 = `data/corpus/` 的一级目录（改语料目录时这里要跟着改，测试会提醒）；
2. 明确**不覆盖**什么 —— 不是"什么都能答"；
3. 三条示例问题（界面上做成可点的 chip）。

界面从 `/api/health` 拿到它；`/api/ask` 用它识别"元问题"（**不检索、不花钱**，直接回这段说明）。
"""

from __future__ import annotations

# 能答的范围：与 data/corpus 下的一级目录一致（2026-10-21：56 篇 / 7 个子主题）
SUBTOPICS: tuple[str, ...] = (
    "刀具磨损监测",
    "切削参数优化",
    "数字孪生与智能车间",
    "数控编程与轨迹规划",
    "机床误差补偿",
    "AI 辅助工艺编制",
    "NC 代码生成与校验",
)

NOT_COVERED: tuple[str, ...] = (
    "表格与公式的**结构**（解析会丢，引用到的数值必须回原文核对）",
    "与上述 7 个子主题无关的问题（会明确说“资料中没有”，不硬答）",
    "**专业正确性判断**——引用可以逐条回查，但结论在专业上对不对仍需人来判断",
)

# 界面上做成可点的示例：覆盖不同子主题，且都是"能答出四段式"的那一类
EXAMPLES: tuple[str, ...] = (
    "刀具磨损监测有哪些主流方法，各自优缺点？",
    "五轴机床后置处理怎么把刀位文件转成 NC 代码？",
    "AI 辅助工艺编制现在有哪些技术路线？",
)

ONE_LINER = (
    "本系统只回答这 7 个子主题（本地 56 篇论文）；资料不足时会明说“资料中没有”，不硬答；"
    "引用可逐条回查，但结论的专业正确性仍需人判断。"
)

# 元问题的识别：**只认短句 + 明确措辞**。宁可漏判（走正常检索、多花一分钱），
# 也不要误判（把正常问题当成元问题、直接回一段说明，等于把用户的问题吞掉）。
#
# 踩过的：第一版收了"怎么用 / 如何使用"，结果「数字孪生在机床上怎么用？」这种**正常问题**
# 被当成元问题拦下了（`test_web` 的会话隔离测试当场红）。所以**不收**这类通用动词短语，
# 只收"主语是系统本身"的措辞。
_CAPABILITY_MARKERS = (
    "你能回答",
    "能回答什么",
    "你会什么",
    "能问什么",
    "可以问什么",
    "能做什么",
    "能干什么",
    "有什么功能",
    "支持哪些",
    "你是谁",
)
_MAX_META_CHARS = 24


def is_capability_question(question: str) -> bool:
    """是不是在问"你能干什么"（而不是问资料里的内容）。"""
    text = (question or "").strip()
    if not text or len(text) > _MAX_META_CHARS:
        return False
    lowered = text.casefold()
    return any(marker in lowered for marker in _CAPABILITY_MARKERS)


def summary() -> dict:
    """给界面 / 健康检查用的能力说明（结构稳定，前端直接读）。"""
    return {
        "one_liner": ONE_LINER,
        "subtopics": list(SUBTOPICS),
        "not_covered": list(NOT_COVERED),
        "examples": list(EXAMPLES),
    }
